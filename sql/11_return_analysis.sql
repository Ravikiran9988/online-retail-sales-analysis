-- 11_return_analysis.sql
-- Uses the raw table because the main cleaned table excludes cancellation invoices.
SELECT
    COUNT_IF(TRIM(TO_VARCHAR(INVOICENO)) ILIKE 'C%') AS CANCELLED_LINE_COUNT,
    COUNT(DISTINCT IFF(TRIM(TO_VARCHAR(INVOICENO)) ILIKE 'C%', INVOICENO, NULL)) AS CANCELLED_INVOICE_COUNT,
    SUM(IFF(TRIM(TO_VARCHAR(INVOICENO)) ILIKE 'C%', ABS(TRY_TO_NUMBER(QUANTITY)), 0)) AS CANCELLED_UNITS,
    ROUND(SUM(IFF(TRIM(TO_VARCHAR(INVOICENO)) ILIKE 'C%',
                  ABS(TRY_TO_NUMBER(QUANTITY) * TRY_TO_DOUBLE(UNITPRICE)), 0)), 2) AS CANCELLED_LINE_VALUE
FROM SALES_PROJECT.PUBLIC.RAW_ONLINE_RETAIL;

-- Monthly view of cancellation activity
SELECT
    DATE_TRUNC('MONTH', TRY_TO_TIMESTAMP_NTZ(INVOICEDATE))::DATE AS SALES_MONTH,
    COUNT(DISTINCT IFF(TRIM(TO_VARCHAR(INVOICENO)) ILIKE 'C%', INVOICENO, NULL)) AS CANCELLED_INVOICES,
    ROUND(SUM(IFF(TRIM(TO_VARCHAR(INVOICENO)) ILIKE 'C%',
                  ABS(TRY_TO_NUMBER(QUANTITY) * TRY_TO_DOUBLE(UNITPRICE)), 0)), 2) AS CANCELLED_VALUE
FROM SALES_PROJECT.PUBLIC.RAW_ONLINE_RETAIL
WHERE TRY_TO_TIMESTAMP_NTZ(INVOICEDATE) IS NOT NULL
GROUP BY 1
ORDER BY 1;
