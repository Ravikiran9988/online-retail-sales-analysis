CREATE OR REPLACE TABLE SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL AS
WITH STANDARDIZED AS (
    SELECT
        TRIM(INVOICENO) AS INVOICENO,
        TRIM(STOCKCODE) AS STOCKCODE,
        COALESCE(
            NULLIF(TRIM(DESCRIPTION), ''),
            'Unknown Product'
        ) AS DESCRIPTION,
        QUANTITY,
        TRY_TO_TIMESTAMP_NTZ(
            TRIM(INVOICEDATE),
            'DD-MM-YYYY HH24:MI'
        ) AS INVOICE_DATE,
        UNITPRICE,
        CUSTOMERID,
        INITCAP(TRIM(COUNTRY)) AS COUNTRY
    FROM SALES_PROJECT.PUBLIC.RAW_ONLINE_RETAIL
),
DEDUPLICATED AS (
    SELECT *
    FROM STANDARDIZED
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY
            INVOICENO, STOCKCODE, DESCRIPTION, QUANTITY,
            INVOICE_DATE, UNITPRICE, CUSTOMERID, COUNTRY
        ORDER BY INVOICENO
    ) = 1
)
SELECT
    INVOICENO,
    STOCKCODE,
    DESCRIPTION,
    QUANTITY,
    INVOICE_DATE,
    UNITPRICE,
    CUSTOMERID,
    COUNTRY,
    QUANTITY * UNITPRICE AS SALES_AMOUNT
FROM DEDUPLICATED
WHERE INVOICE_DATE IS NOT NULL
  AND INVOICENO NOT LIKE 'C%'
  AND QUANTITY > 0
  AND UNITPRICE > 0;

  SELECT
    COUNT(*) AS CLEANED_ROWS,
    SUM(SALES_AMOUNT) AS TOTAL_REVENUE,
    COUNT(DISTINCT INVOICENO) AS TOTAL_INVOICES
FROM SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL;

SELECT
    DATE_TRUNC('MONTH', INVOICE_DATE) AS SALES_MONTH,
    COUNT(DISTINCT INVOICENO) AS TOTAL_INVOICES,
    SUM(QUANTITY) AS TOTAL_UNITS_SOLD,
    ROUND(SUM(SALES_AMOUNT), 2) AS MONTHLY_REVENUE
FROM SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL
GROUP BY DATE_TRUNC('MONTH', INVOICE_DATE)
ORDER BY SALES_MONTH;

SELECT
    STOCKCODE,
    DESCRIPTION,
    SUM(QUANTITY) AS TOTAL_UNITS_SOLD,
    ROUND(SUM(SALES_AMOUNT), 2) AS TOTAL_REVENUE
FROM SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL
GROUP BY STOCKCODE, DESCRIPTION
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

SELECT
    COUNTRY,
    COUNT(DISTINCT INVOICENO) AS TOTAL_INVOICES,
    ROUND(SUM(SALES_AMOUNT), 2) AS TOTAL_REVENUE
FROM SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL
GROUP BY COUNTRY
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

SELECT
    TO_CHAR(INVOICE_DATE, 'YYYY-MM') AS SALES_MONTH,
    ROUND(SUM(SALES_AMOUNT), 2) AS MONTHLY_REVENUE
FROM SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL
GROUP BY TO_CHAR(INVOICE_DATE, 'YYYY-MM')
ORDER BY MONTHLY_REVENUE DESC
LIMIT 1;
