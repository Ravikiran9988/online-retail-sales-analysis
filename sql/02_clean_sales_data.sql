-- 02_clean_sales_data.sql
-- Rebuilds the cleaned sales table used by the analysis and dashboard.
-- The source date values use the format DD-MM-YYYY HH24:MI.

CREATE OR REPLACE TABLE SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL AS
WITH STANDARDIZED AS (
    SELECT
        TRIM(TO_VARCHAR(INVOICENO)) AS INVOICENO,
        TRIM(TO_VARCHAR(STOCKCODE)) AS STOCKCODE,
        COALESCE(NULLIF(TRIM(TO_VARCHAR(DESCRIPTION)), ''), 'Unknown Product') AS DESCRIPTION,
        TRY_TO_NUMBER(QUANTITY) AS QUANTITY,
        TRY_TO_TIMESTAMP_NTZ(TRIM(TO_VARCHAR(INVOICEDATE)), 'DD-MM-YYYY HH24:MI') AS INVOICE_DATE,
        TRY_TO_DOUBLE(UNITPRICE) AS UNITPRICE,
        TRY_TO_NUMBER(CUSTOMERID) AS CUSTOMERID,
        INITCAP(TRIM(TO_VARCHAR(COUNTRY))) AS COUNTRY
    FROM SALES_PROJECT.PUBLIC.RAW_ONLINE_RETAIL
),
DEDUPLICATED AS (
    SELECT *
    FROM STANDARDIZED
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY INVOICENO, STOCKCODE, DESCRIPTION, QUANTITY,
                     INVOICE_DATE, UNITPRICE, CUSTOMERID, COUNTRY
        ORDER BY INVOICENO
    ) = 1
)
SELECT
    INVOICENO,
    STOCKCODE,
    DESCRIPTION,
    QUANTITY,
    INVOICE_DATE,
    UNITPRICE,
    CUSTOMERID,
    COUNTRY,
    QUANTITY * UNITPRICE AS SALES_AMOUNT
FROM DEDUPLICATED
WHERE INVOICE_DATE IS NOT NULL
  AND INVOICENO IS NOT NULL
  AND INVOICENO NOT ILIKE 'C%'
  AND QUANTITY > 0
  AND UNITPRICE > 0;
