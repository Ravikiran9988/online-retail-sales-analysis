-- Monthly revenue, order volume, and month-over-month change.
WITH monthly AS (
    SELECT
        DATE_TRUNC('MONTH', INVOICE_DATE)::DATE AS SALES_MONTH,
        ROUND(SUM(SALES_AMOUNT), 2) AS REVENUE,
        COUNT(DISTINCT INVOICENO) AS INVOICES,
        SUM(QUANTITY) AS UNITS_SOLD
    FROM SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL
    GROUP BY 1
)
SELECT
    SALES_MONTH,
    REVENUE,
    INVOICES,
    UNITS_SOLD,
    LAG(REVENUE) OVER (ORDER BY SALES_MONTH) AS PREVIOUS_MONTH_REVENUE,
    ROUND(100.0 * (REVENUE - LAG(REVENUE) OVER (ORDER BY SALES_MONTH))
          / NULLIF(LAG(REVENUE) OVER (ORDER BY SALES_MONTH), 0), 2) AS REVENUE_MOM_CHANGE_PCT
FROM monthly
ORDER BY SALES_MONTH;
