-- RFM-inspired spend segments based on total customer spend.
WITH customer_spend AS (
    SELECT
        CUSTOMERID,
        SUM(SALES_AMOUNT) AS TOTAL_SPEND,
        COUNT(DISTINCT INVOICENO) AS INVOICE_COUNT,
        MAX(INVOICE_DATE)::DATE AS LAST_PURCHASE_DATE
    FROM SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL
    WHERE CUSTOMERID IS NOT NULL
    GROUP BY CUSTOMERID
),
segmented AS (
    SELECT *,
        CASE
            WHEN TOTAL_SPEND >= 5000 THEN 'High Value'
            WHEN TOTAL_SPEND >= 1000 THEN 'Medium Value'
            ELSE 'Low Value'
        END AS CUSTOMER_SEGMENT
    FROM customer_spend
)
SELECT
    CUSTOMER_SEGMENT,
    COUNT(*) AS CUSTOMER_COUNT,
    ROUND(AVG(TOTAL_SPEND), 2) AS AVERAGE_CUSTOMER_SPEND,
    ROUND(SUM(TOTAL_SPEND), 2) AS SEGMENT_REVENUE,
    SUM(INVOICE_COUNT) AS TOTAL_INVOICES
FROM segmented
GROUP BY CUSTOMER_SEGMENT
ORDER BY SEGMENT_REVENUE DESC;
