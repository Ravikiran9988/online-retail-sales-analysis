-- Final row-level and KPI checks for the cleaned dataset.
SELECT
    COUNT(*) AS CLEAN_ROW_COUNT,
    ROUND(SUM(SALES_AMOUNT), 2) AS TOTAL_REVENUE,
    COUNT(DISTINCT INVOICENO) AS TOTAL_INVOICES,
    COUNT(DISTINCT CUSTOMERID) AS UNIQUE_CUSTOMERS,
    COUNT(DISTINCT STOCKCODE) AS UNIQUE_PRODUCTS,
    SUM(QUANTITY) AS UNITS_SOLD,
    MIN(INVOICE_DATE)::DATE AS FIRST_INVOICE_DATE,
    MAX(INVOICE_DATE)::DATE AS LAST_INVOICE_DATE
FROM SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL;

-- Expected cleaning invariants: each count below should be zero.
SELECT
    COUNT_IF(INVOICE_DATE IS NULL) AS NULL_DATES,
    COUNT_IF(QUANTITY <= 0) AS NON_POSITIVE_QUANTITY,
    COUNT_IF(UNITPRICE <= 0) AS NON_POSITIVE_PRICE,
    COUNT_IF(ABS(SALES_AMOUNT - (QUANTITY * UNITPRICE)) > 0.0001) AS SALES_AMOUNT_MISMATCH,
    COUNT_IF(INVOICENO ILIKE 'C%') AS CANCELLED_INVOICES_REMAINING
FROM SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL;
