-- 02_clean_sales_data.sql
-- Creates the cleaned sales table used by the reports and dashboard.
-- Adjust source column names if your raw table uses different casing/names.

CREATE OR REPLACE TABLE SALES_PROJECT.PUBLIC.CLEAN_ONLINE_RETAIL AS
SELECT
    TRIM(TO_VARCHAR(INVOICENO)) AS INVOICENO,
    TRIM(TO_VARCHAR(STOCKCODE)) AS STOCKCODE,
    NULLIF(TRIM(TO_VARCHAR(DESCRIPTION)), '') AS DESCRIPTION,
    TRY_TO_NUMBER(QUANTITY) AS QUANTITY,
    TRY_TO_TIMESTAMP_NTZ(INVOICEDATE) AS INVOICE_DATE,
    TRY_TO_DOUBLE(UNITPRICE) AS UNITPRICE,
    TRY_TO_NUMBER(CUSTOMERID) AS CUSTOMERID,
    TRIM(TO_VARCHAR(COUNTRY)) AS COUNTRY,
    TRY_TO_NUMBER(QUANTITY) * TRY_TO_DOUBLE(UNITPRICE) AS SALES_AMOUNT
FROM SALES_PROJECT.PUBLIC.RAW_ONLINE_RETAIL
WHERE INVOICENO IS NOT NULL
  AND INVOICEDATE IS NOT NULL
  AND TRY_TO_TIMESTAMP_NTZ(INVOICEDATE) IS NOT NULL
  AND NOT TRIM(TO_VARCHAR(INVOICENO)) ILIKE 'C%'
  AND TRY_TO_NUMBER(QUANTITY) > 0
  AND TRY_TO_DOUBLE(UNITPRICE) > 0
  AND COUNTRY IS NOT NULL;
